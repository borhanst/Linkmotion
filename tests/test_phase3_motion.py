# --------------------------------------------------------------------------- #

@pytest.mark.skipif(not _edge_tts_available(), reason="edge-tts unavailable")
def test_tts_word_timestamps(tmp_path: Path) -> None:
    from tools.tts import TTSTool
    r = TTSTool().synthesize("Hello world today", str(tmp_path / "a.mp3"))
    assert r.ok
    words = r.words
    assert len(words) >= 3
    starts = [w["start"] for w in words]
    assert starts == sorted(starts)
    assert len({w["start"] for w in words}) == len(words), "each word needs its own start"
    for w in words:
        assert w["end"] > w["start"]


