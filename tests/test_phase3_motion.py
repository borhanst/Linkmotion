# --------------------------------------------------------------------------- #
# html_render - frame-stepped deterministic rendering
# --------------------------------------------------------------------------- #

TEST_SCENE = """<!DOCTYPE html>
<html><head>
<script src="https://cdnjs.cloudflare.com/ajax/libs/gsap/3.12.2/gsap.min.js"></script>
<style>body{margin:0;background:#0A0A0F}#box{width:100px;height:100px;background:#7C3AED}</style>
</head><body><div id="box"></div>
<script>
  gsap.from("#box", { duration: 0.8, opacity: 0, scale: 0.5, ease: "power2.out" });
  gsap.to("#box", { duration: 0.5, x: 40, delay: 1.0 });
</script></body></html>
"""


@pytest.mark.skipif(not FFMPEG, reason="ffmpeg unavailable")
def test_frames_render_deterministic(tmp_path: Path) -> None:
    from tools.html_render import HtmlRenderTool
    page = tmp_path / "scene.html"
    page.write_text(TEST_SCENE, encoding="utf-8")
    tool = HtmlRenderTool()
    a, b = tmp_path / "a.mp4", tmp_path / "b.mp4"
    r1 = tool.render(str(page), str(a), duration_sec=1.0, fps=8, viewport=[320, 200], mode="frames")
    assert r1["ok"], r1.get("error")
    assert r1["mode"] == "frames" and r1["frames"] == 8
    assert abs(r1["duration_sec"] - 1.0) < 0.3
    r2 = tool.render(str(page), str(b), duration_sec=1.0, fps=8, viewport=[320, 200], mode="frames")
    assert r2["ok"], r2.get("error")
    assert hashlib.md5(a.read_bytes()).digest() == hashlib.md5(b.read_bytes()).digest()


@pytest.mark.skipif(not FFMPEG, reason="ffmpeg unavailable")
def test_render_auto_falls_back_to_record_without_gsap(tmp_path: Path) -> None:
    from tools.html_render import HtmlRenderTool
    page = tmp_path / "static.html"
    page.write_text("<!DOCTYPE html><html><body><p style='font-size:40px'>none</p></body></html>",
                    encoding="utf-8")
    out = tmp_path / "out.mp4"
