# --------------------------------------------------------------------------- #
# lib.captions - word grouping
# --------------------------------------------------------------------------- #

WORDS = [
    {"word": "Claude", "start": 0.10, "end": 0.40},
    {"word": "Ultra", "start": 0.45, "end": 0.80},
    {"word": "just", "start": 0.85, "end": 1.00},
    {"word": "dropped", "start": 1.05, "end": 1.40},
    {"word": "it.", "start": 1.45, "end": 1.70},
    {"word": "Wow", "start": 2.60, "end": 2.90},   # after a 0.9s gap -> own chunk
]


def test_group_words_pairs_by_default() -> None:
    from lib.captions import group_words
    chunks = group_words(WORDS, max_words=2)
    assert [c["plain"] for c in chunks] == [
        "Claude Ultra", "just dropped", "it.", "Wow",
    ]
    assert chunks[0]["start"] == 0.10 and chunks[0]["end"] == 0.80
    assert chunks[-1]["start"] == 2.60


def test_group_words_breaks_on_big_gap() -> None:
    from lib.captions import group_words
    # No punctuation; the only break comes from the 0.9s silence gap.
    words = [{"word": w, "start": s, "end": s + 0.2} for w, s in
             [("a", 0.0), ("b", 0.3), ("c", 1.2), ("d", 1.5)]]
    chunks = group_words(words, max_words=4, gap_break=0.5)
    assert [c["plain"] for c in chunks] == ["a b", "c d"]


def test_group_words_text_is_html_escaped_with_highlight() -> None:
    from lib.captions import group_words
    chunks = group_words([{"word": '<b>&', "start": 0.0, "end": 0.1}], max_words=2)
    assert "&lt;b&gt;" in chunks[0]["text"]
    assert 'span class="hl"' in chunks[0]["text"]


def test_burn_injects_and_replaces(tmp_path: Path) -> None:
    from lib.captions import burn
    html = tmp_path / "beat.html"
    html.write_text("<!DOCTYPE html><html><body><h1>beat</h1></body>\n", encoding="utf-8")

    r1 = burn(str(html), WORDS, str(html))
    assert r1["ok"] and len(r1["chunks"]) == 4
    text = html.read_text(encoding="utf-8")
    assert "cap-track" in text
    assert text.count("<!-- CAPTION-TRACK (generated by lib.captions) -->") == 1
    assert text.index("cap-track") < text.index("</body>")

    # Re-burn replaces the existing block instead of duplicating it.
    r2 = burn(str(html), WORDS, str(html))
    assert r2["ok"]
    text2 = html.read_text(encoding="utf-8")
    assert text2.count("<!-- CAPTION-TRACK (generated by lib.captions) -->") == 1

    # out_html defaults to overwriting the source; explicit path writes there.
    dst = tmp_path / "burned.html"
    r3 = burn(str(html), WORDS, str(dst), font_size=48)
    assert r3["ok"] and dst.is_file()


