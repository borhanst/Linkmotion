"""Word-timed caption choreography for HTML beats.

Group edge-tts word timestamps (``{"word", "start", "end"}``) into caption
chunks of 1-2 words that pop in/out exactly on the beat of the narration, and
burn them into a beat's HTML as a GSAP-driven ``.cap-track`` overlay.

The burned tweens are top-level ``gsap.to`` calls, so the frame-stepped
renderer (``tools/html_render.py`` mode="frames") captures and drives them
exactly like any other page animation.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

# Markers so re-burning a previously burned file replaces (not duplicates).
_BEGIN = "<!-- CAPTION-TRACK (generated by lib.captions) -->"
_END = "<!-- /CAPTION-TRACK -->"

# Injected CSS: bottom overlay inside the vertical safe zone
# (1080x1920 Shorts: keep captions above ~380px from the bottom).
_CSS_TEMPLATE = """
  <style>
    %SELECTOR% {
      position: absolute;
      left: 50%%;
      bottom: %BOTTOM%px;
      transform: translateX(-50%%);
      width: %WIDTH%px;
      text-align: center;
      pointer-events: none;
      z-index: 50;
    }
    %SELECTOR% .cap-chunk {
      display: inline-block;
      font-family: %FONT_FAMILY%;
      font-size: %FONT_SIZE%px;
      font-weight: 800;
      line-height: 1.12;
      color: %COLOR%;
      background: %BACKGROUND%;
      padding: %PAD_Y%px %PAD_X%px;
      border-radius: %RADIUS%px;
      letter-spacing: -0.5px;
      white-space: nowrap;
    }
    %SELECTOR% .cap-chunk .hl { color: %HIGHLIGHT%; }
  </style>
"""


def group_words(words: list[dict[str, Any]], max_words: int = 2,
                max_chars: int | None = None, gap_break: float = 0.5) -> list[dict[str, Any]]:
    """Split a word stream into caption chunks shown 1..max_words at a time.

    A chunk boundary is forced when the word count hits ``max_words``, the
    chunk text reaches ``max_chars``, a silent gap > ``gap_break`` seconds
    separates consecutive words, or the previous word ends in punctuation.
    """
    chunks: list[dict[str, Any]] = []
    cur: list[dict[str, Any]] = []

    def flush() -> None:
        if not cur:
            return
        chunks.append({
            "text": _highlight_text(cur),
            "plain": " ".join(w["word"] for w in cur),
            "start": round(cur[0]["start"], 3),
            "end": round(cur[-1]["end"], 3),
        })
        cur.clear()

    for i, w in enumerate(words):
        cur.append(w)
        plain = " ".join(c["word"] for c in cur)
        ends_sentence = w["word"].rstrip().endswith((".", "!", "?", "\u2014", "\u2013", ":"))
        if len(cur) >= max_words or (max_chars is not None and len(plain) >= max_chars) or ends_sentence:
            flush()
            continue
        nxt = words[i + 1] if i + 1 < len(words) else None
        if nxt is None or (nxt["start"] - w["end"]) > gap_break:
            flush()

    flush()
    return chunks


def _highlight_text(words_in_chunk: list[dict[str, Any]]) -> str:
    """Escape words; the last word of a chunk gets a highlight span (punch word)."""
    parts: list[str] = []
    for j, w in enumerate(words_in_chunk):
        text = _esc(w["word"])
        if j == len(words_in_chunk) - 1:
            parts.append(f'<span class="hl">{text}</span>')
        else:
            parts.append(text)
    return " ".join(parts)


def _esc(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace('"', "&quot;"))


def build_caption_snippet(chunks: list[dict[str, Any]], selector: str = ".cap-track",
                          in_dur: float = 0.18, ease: str = "back.out(2)",
                          out_dur: float = 0.14, out_fade: bool = True) -> str:
    """Build the GSAP `<script>` that shows/hides each chunk at narration time.

    Chunks appear at ``start`` with a pop-in; they pop out just before the next
    chunk appears (or fade at ``end`` when a gap follows). All tweens are
    top-level gsap calls with explicit positions via delay, so the captured
    master timeline reproduces them exactly during frame-stepped rendering.
    """
    lines: list[str] = [
        "(function () {",
        f'  const track = document.querySelector("{_js_esc(selector)}");',
        "  if (!track) return;",
        "  function makeChunk(i) {",
        "    const el = document.createElement('div');",
        "    el.className = 'cap-chunk';",
        "    el.innerHTML = CHUNK_DATA[i].text;",
        "    track.appendChild(el);",
        "    gsap.set(el, { opacity: 0, y: 24, scale: 0.9 });",
        "    return el;",
        "  }",
        "  const CHUNK_DATA = " + json.dumps(
            [{"text": c["text"], "start": c["start"], "end": c["end"]} for c in chunks]),
        f"  const IN_DUR = {in_dur}, OUT_DUR = {out_dur};",
        "  const seen = {};",
        "  CHUNK_DATA.forEach((c, i) => {",
        "    const next = CHUNK_DATA[i + 1];",
        f"    gsap.to(makeChunk(i), {{ opacity: 1, y: 0, scale: 1, duration: IN_DUR,"
        f" ease: {_js_literal(ease)}, delay: c.start }});",
        "    let outAt = c.end - OUT_DUR;",
        "    if (next && next.start - c.end < OUT_DUR + 0.02) outAt = next.start - 0.001;",
        "    if (out_fade_enabled(outAt)) ",
        "      gsap.to(CHUNK_DATA[i].el, { opacity: 0, y: -14, duration: OUT_DUR, delay: outAt });",
        "  });",
        "})();",
    ]
    snippet = "\n".join(_LINE_TEMPLATES)
    # Trivial replacement placeholders resolved below.
    for k, v in {
        "__SELECTOR__": _js_esc(selector),
        "__CHUNK_DATA__": json.dumps([{"text": c["text"], "start": c["start"], "end": c["end"]} for c in chunks]),
        "__IN_DUR__": repr(in_dur),
        "__OUT_DUR__": repr(out_dur),
        "__EASE__": _js_literal(ease),
    }.items():
        snippet = snippet.replace(k, v)
    return snippet


# Chunk elements are referenced through an array so both the in-tween and the
# out-tween target the same node.
_SCRIPT_TEMPLATE = """<script>
(function () {
  var track = document.querySelector("%SELECTOR%");
  if (!track) return;
  var DATA = %CHUNK_DATA%;
  var els = DATA.map(function (c) {
    var el = document.createElement("div");
    el.className = "cap-chunk";
    el.innerHTML = c.text;
    track.appendChild(el);
    gsap.set(el, { opacity: 0, y: 24, scale: 0.9 });
    return el;
  });
  DATA.forEach(function (c, i) {
    var next = DATA[i + 1];
    gsap.to(els[i], { opacity: 1, y: 0, scale: 1, duration: %IN_DUR%, ease: %EASE%, delay: c.start });
    var outAt = c.end - %OUT_DUR%;
    if (next && (next.start - c.end) < %OUT_DUR% + 0.02) outAt = next.start - 0.001;
    gsap.to(els[i], { opacity: 0, y: -12, duration: %OUT_DUR%, delay: outAt });
  });
})();
</script>"""


def burn(html_path: str, words: list[dict[str, Any]], out_html: str | None = None, **opts: Any) -> dict[str, Any]:
    """Burn word-timed captions into a beat HTML file.

    Injects a styled `.cap-track` div + GSAP script before `</body>` between
    marker comments; if markers already exist (re-burn), the previous track is
    replaced. `opts` (see ``_CSS_TEMPLATE``): selector, bottom, width,
    font_size, colors, in_dur/out_dur, ease, max_words.

    Returns {"ok", "out_html", "chunks", "path"}.
    """
    src = Path(html_path)
    html = src.read_text(encoding="utf-8")

    selector = opts.get("selector", ".cap-track")
    bottom = opts.get("bottom", 300)
    width = opts.get("width", 880)
    font_size = opts.get("font_size", 64)
    font_family = opts.get("font_family", "var(--font-display, 'Inter', system-ui, sans-serif)")
    color = opts.get("color", "#FFFFFF")
    background = opts.get("background", "rgba(10, 10, 15, 0.72)")
    radius = opts.get("radius", 18)
    pad_x = opts.get("pad_x", 28)
    pad_y = opts.get("pad_y", 10)
    highlight = opts.get("highlight", "#7C3AED")
    in_dur = opts.get("in_dur", 0.18)
    out_dur = opts.get("out_dur", 0.14)
    ease = opts.get("ease", "back.out(2)")
    max_words = opts.get("max_words", 2)

    chunks = group_words(words, max_words=max_words, max_chars=opts.get("max_chars"))
    if not chunks:
        return {"ok": False, "out_html": str(out_html or html_path), "error": "no words to caption"}

    css = (
        _CSS_TEMPLATE
        .replace("%SELECTOR%", _css_esc(selector))
        .replace("%BOTTOM%", str(bottom)).replace("%WIDTH%", str(width))
        .replace("%FONT_SIZE%", str(font_size)).replace("%FONT_FAMILY%", font_family)
        .replace("%COLOR%", color).replace("%BACKGROUND%", background)
        .replace("%RADIUS%", str(radius)).replace("%PAD_X%", str(pad_x)).replace("%PAD_Y%", str(pad_y))
        .replace("%HIGHLIGHT%", highlight)
        .replace("%%", "%")
    )
    script = (
        _SCRIPT_TEMPLATE
        .replace("%SELECTOR%", _js_esc(selector))
        .replace("%CHUNK_DATA%", json.dumps(
            [{"text": c["text"], "start": c["start"], "end": c["end"]} for c in chunks]))
        .replace("%IN_DUR%", repr(in_dur)).replace("%OUT_DUR%", repr(out_dur))
        .replace("%EASE%", _js_literal(ease))
    )
    block = _BEGIN + css + f'\n  <div class="{_class_name(selector)}"></div>\n' + script + _END

    # Replace an existing burned block, else append before </body>.
    pattern = re.compile(re.escape(_BEGIN) + r".*?" + re.escape(_END), re.DOTALL)
    if pattern.search(html):
        html = pattern.sub(lambda _m: block, html, count=1)
    elif "</body>" in html:
        html = html.replace("</body>", block + "\n</body>", 1)
    else:
        return {"ok": False, "out_html": str(out_html or html_path), "error": "no </body> tag found"}

    out = Path(out_html) if out_html else src
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")
    return {"ok": True, "out_html": str(out), "chunks": chunks, "path": str(out)}


def _class_name(selector: str) -> str:
    return selector.lstrip(" .#").strip()


def _css_esc(selector: str) -> str:
    # Selectors we generate are simple classes/ids; pass through as-is.
    return selector


def _js_esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _js_literal(ease: str) -> str:
    """Quote/ease strings into valid JS literals (e.g. back.out(2) -> "back.out(2)")."""
    if ease and ease[0] in "\"'":
        return ease
    return '"' + ease.replace('"', '\\"') + '"'


def load_words(words_json: str) -> list[dict[str, Any]]:
    data = json.loads(Path(words_json).read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise ValueError("words file must be a JSON list of {word, start, end}")
    return data


def _main() -> None:  # pragma: no cover
    import sys
    if len(sys.argv) == 4 and sys.argv[1] == "group":
        words = load_words(sys.argv[2])
        print(json.dumps(group_words(words), indent=2))
        return
    if len(sys.argv) == 5 and sys.argv[1] == "burn":
        r = burn(sys.argv[2], load_words(sys.argv[3]), sys.argv[4])
        print(json.dumps(r, indent=2))
        return
    print(__doc__)
    print("usage: python -m lib.captions group <words.json> | burn <beat.html> <words.json> <out.html>")


if __name__ == "__main__":
    _main()
